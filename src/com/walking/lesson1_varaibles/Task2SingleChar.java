package com.walking.lesson1_varaibles;

/**
 * Используя одну переменную типа char вывести свое имя в консоль.
 */
public class Task2SingleChar {
    public static void main(String[] args) {
        char letter = 'A';
        System.out.print(letter);
        letter = 'l';
        System.out.print(letter);
        letter = 'e';
        System.out.print(letter);
        letter = 'k';
        System.out.print(letter);
        letter = 's';
        System.out.print(letter);
        letter = 'e';
        System.out.print(letter);
        letter = 'y';
        System.out.print(letter);
    }
}
